    // Método para agregar una calificación como una nueva fila en la tabla
    public void addNota(Calificacion cali) {
        // Obtenemos el modelo de la tabla
        javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) jTable1.getModel();

        // Añadimos una nueva fila con los datos del objeto Calificacion
        modelo.addRow(new Object[]{
            cali.getId_calificacion(),
            cali.getId_detalle_matricula(),
            cali.getMombre_evaluacion(), // (Ojo con el typo 'mombre' en tu modelo)
            cali.getPonderado(),
            cali.getNota(),
            cali.getFecha_registro()
        });
    }

