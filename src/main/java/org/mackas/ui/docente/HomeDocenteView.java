    public HomeDocenteView(Docente docente) {
        initComponents();
        this.docente = docente;
        secciones = null;

        // 1. Validar que existan secciones para evitar IndexOutOfBoundsException
        if (secciones != null && !secciones.isEmpty()) {
            seccion = secciones.get(0);
            navegador = new Navegacion(seccion);

            // 2. Configurar el layout del contenedor
            contenedorNavigator.setLayout(new java.awt.BorderLayout());

            // 3. Limpiar y agregar el nuevo panel
            contenedorNavigator.removeAll();
            contenedorNavigator.add(navegador, java.awt.BorderLayout.CENTER);

            // 4. FORZAR EL REDIBUJADO (Esto es lo que faltaba)
            contenedorNavigator.revalidate(); // Re-calcula la distribución de componentes
            contenedorNavigator.repaint();    // Vuelve a pintar el contenedor en pantalla
        }
    }

